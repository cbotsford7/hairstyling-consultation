		// PRODUCT PREVIEW
		// ============================================================
		
		function showProductPreview(productID) {
		
		    if (!root.productPreviewMC) {
		        return;
		    }
		
		
		    var source = getInstance(productID);
		
		
		    if (!source) {
		        return;
		    }
		
		
		    root.productPreviewMC.removeAllChildren();
		
		
		    var clone = source.clone();
		
		
		    clone.visible = true;
		
		    clone.x = 0;
		
		    clone.y = 0;
		
		    clone.scaleX = 1;
		
		    clone.scaleY = 1;
		
		
		    var bounds = clone.getBounds();
		
		
		    if (bounds) {
		
		        var height = bounds.height;
		
		
		        if (height > 0) {
		
		            var scale =
		                PRODUCT_PREVIEW_HEIGHT / height;
		
		
		            clone.scaleX = scale;
		
		            clone.scaleY = scale;
		
		
		            bounds = clone.getBounds();
		
		
		            clone.x =
		                -(bounds.x + bounds.width / 2);
		
		
		            clone.y =
		                -(bounds.y + bounds.height / 2);
		        }
		    }
		
		
		    root.productPreviewMC.addChild(clone);
		
		
		    root.productPreviewMC.x =
		        PRODUCT_PREVIEW_X;
		
		
		    root.productPreviewMC.y =
		        PRODUCT_PREVIEW_Y;
		
		
		    root.productPreviewMC.visible = true;
		}
		
		
