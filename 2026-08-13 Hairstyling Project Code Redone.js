		// ============================================================
		// SHOW FEEDBACK POPUP
		// ============================================================
		
		function showFeedback(productID) {
		
		    var popup = getPopup();
		
		
		    if (!popup) {
		        return;
		    }
		
		
		    var goodChoice = isGoodChoice(productID);
		
		
		    // ========================================================
		    // SCORING
		    // ========================================================
		
		    if (!goodChoice) {
		
		        // Wrong product selection
		        wrongClicks++;
		
		        root._hairstylingWrongClicks =
		            wrongClicks;
		
		    } else {
		
		        // Correct product selection
		        //
		        // Client 3 + Redken Spray Wax is specifically
		        // classified as an Excellent / Great choice.
		        if (
		            currentClient === 3 &&
		            productID === "RSWbtn"
		        ) {
		
		            greatChoices++;
		
		            root._hairstylingGreatChoices =
		                greatChoices;
		
		        } else {
		
		            // Other correct choices
		            //
		            // We determine whether the existing feedback
		            // is "Excellent Choice!" or "Good Choice!"
		            var positiveText =
		                getPositiveFeedback(productID);
		
		
		            if (
		                positiveText.indexOf("Excellent choice!") === 0 ||
		                positiveText.indexOf("Excellent Choice!") === 0
		            ) {
		
		                greatChoices++;
		
		                root._hairstylingGreatChoices =
		                    greatChoices;
		
		            } else {
		
		                goodChoices++;
		
		                root._hairstylingGoodChoices =
		                    goodChoices;
		            }
		        }
		    }
		
		
		    // ========================================================
		    // LOCK AFTER CORRECT ANSWER
		    // ========================================================
		
		    if (goodChoice) {
		
		        selectionLocked = true;
		
		        root._hairstylingSelectionLocked = true;
		
		    } else {
		
		        selectionLocked = false;
		
		        root._hairstylingSelectionLocked = false;
		    }
		
		
		    // ========================================================
		    // POPUP TITLE
		    // ========================================================
		
		    if (popup.popupTitle_txt) {
		
		        if (
		            currentClient === 3 &&
		            productID === "RSWbtn"
		        ) {
		
		            popup.popupTitle_txt.text =
		                "Excellent Choice!";
		
		        } else if (goodChoice) {
		
		            var feedbackForTitle =
		                getPositiveFeedback(productID);
		
		
		            if (
		                feedbackForTitle.indexOf("Excellent choice!") === 0 ||
		                feedbackForTitle.indexOf("Excellent Choice!") === 0
		            ) {
		
		                popup.popupTitle_txt.text =
		                    "Excellent Choice!";
		
		            } else {
		
		                popup.popupTitle_txt.text =
		                    "Good Choice!";
		            }
		
		        } else {
		
		            popup.popupTitle_txt.text =
		                "Consider Another Option";
		        }
		    }
		
		
		    // ========================================================
		    // POPUP BODY
		    // ========================================================
		
		    if (popup.popupBody_txt) {
		
		        if (goodChoice) {
		
		            popup.popupBody_txt.text =
		                getPositiveFeedback(productID);
		
		        } else {
		
		            popup.popupBody_txt.text =
		                getNegativeFeedback(productID);
		        }
		    }
		
		
		    // ========================================================
		    // POPUP BUTTONS
		    // ========================================================
		
		    if (popup.continueBtn) {
		
		        popup.continueBtn.visible =
		            goodChoice &&
		            currentStep < getMaxStep();
		    }
		
		
		    if (popup.nextClientBtn) {
		
		        popup.nextClientBtn.visible =
		            goodChoice &&
		            currentStep === getMaxStep() &&
		            currentClient < 4;
		    }
		
		
		    if (popup.restartBtn) {
		
		        popup.restartBtn.visible =
		            goodChoice &&
		            currentStep === getMaxStep() &&
		            currentClient === 4;
		    }
		
		
		    // ========================================================
		    // FINAL CLIENT
		    //
		    // Instead of immediately showing the end screen here,
		    // the existing Restart button remains available in the
		    // popup. We will change its behavior below so that it
		    // shows the final results screen.
		    // ========================================================
		
		    popup.visible = true;
		
		    popupOpen = true;
		
		    root._hairstylingPopupOpen = true;
		}
		
		
		// ============================================================
		// ADVANCE STEP
		// ============================================================
		
		function advanceStep() {
		
		    if (currentStep < getMaxStep()) {
		
		        selectionLocked = false;
		
		        root._hairstylingSelectionLocked = false;
		
		
		        currentStep++;
		
		        root._hairstylingCurrentStep =
		            currentStep;
		
		        closePopup();
		
		        updateInterface();
		    }
		}
		
		
		// ============================================================
		// ADVANCE CLIENT
		// ============================================================
		
		function advanceClient() {
		
		    if (currentClient < 4) {
		
		        selectionLocked = false;
		
		        root._hairstylingSelectionLocked = false;
		
		
		        currentClient++;
		
		        root._hairstylingCurrentClient =
		            currentClient;
		
		        currentStep = 1;
		
		        root._hairstylingCurrentStep =
		            currentStep;
		
		        closePopup();
		
		        updateInterface();
		    }
		}
		
		
