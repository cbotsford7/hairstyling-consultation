		// PRODUCT SETUP
		// ============================================================
		
		function setupProduct(productID) {
		
		    var product = getInstance(productID);
		
		
		    if (!product) {
		        return;
		    }
		
		
		    product.cursor = "pointer";
		
		
		    product.addEventListener(
		        "mouseover",
		        function () {
		
		            showProductName(productID);
		
		            showProductPreview(productID);
		        }
		    );
		
		
		    product.addEventListener(
		        "mouseout",
		        function () {
		
		            hideProductName();
		
		            hideProductPreview();
		        }
		    );
		
		
		    product.addEventListener(
		        "click",
		        function () {
		
		            // Cannot select before Start
		            if (!root._hairstylingHasStarted) {
		                return;
		            }
		
		
		            // Cannot select after correct answer
		            if (root._hairstylingSelectionLocked) {
		                return;
		            }
		
		
		            showFeedback(productID);
		        }
		    );
		}
		
		
