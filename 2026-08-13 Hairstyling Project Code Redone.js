		// RESTART / RESET CONSULTATION
		// ============================================================
		
		function restartConsultation() {
		
		    // Reset client
		    currentClient = 1;
		
		    root._hairstylingCurrentClient = 1;
		
		
		    // Reset step
		    currentStep = 1;
		
		    root._hairstylingCurrentStep = 1;
		
		
		    // Reset started state
		    hasStarted = false;
		
		    root._hairstylingHasStarted = false;
		
		
		    // Unlock product selection
		    selectionLocked = false;
		
		    root._hairstylingSelectionLocked = false;
		
		
		    // ========================================================
		    // RESET SCORES
		    // ========================================================
		
		    wrongClicks = 0;
		
		    goodChoices = 0;
		
		    greatChoices = 0;
		
		
		    root._hairstylingWrongClicks = 0;
		
		    root._hairstylingGoodChoices = 0;
		
		    root._hairstylingGreatChoices = 0;
		
		
		    // Close popup
		    closePopup();
		
		
		    // Hide end screen
		    if (root.endScreenMC) {
		
		        root.endScreenMC.visible = false;
		    }
		//fix
		if (root.clientInfoMC) {
		    root.clientInfoMC.visible = false;
		}
		
		if (root.progressMC) {
		    root.progressMC.visible = false;
		}
		
		    // Clear product information
		    hideProductName();
		
		    hideProductPreview();
		
		
		    // Show Start
		    if (root.startBtn) {
		
		        root.startBtn.visible = true;
		    }
		
		
		    // Update interface
		    updateInterface();
		}
		
		
