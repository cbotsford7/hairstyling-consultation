		// ============================================================
		// SETUP PRODUCT
		// ============================================================
		
		function setupProduct(productID) {
		
		    var product =
		        getInstance(productID);
		
		    if (!product) {
		        return;
		    }
		
		
		    product.cursor = "pointer";
		
		
		    // --------------------------------------------------------
		    // MOUSE OVER
		    // --------------------------------------------------------
		
		    product.addEventListener(
		        "mouseover",
		        function () {
		
		            // Normally, popupOpen prevents the product
		            // preview from appearing.
		            //
		            // The exception is a WRONG answer popup.
		            // In that case, leave the popup open and simply
		            // allow the hover preview to appear.
		            //
		            // Do NOT change popupOpen here.
		            // Do NOT close the popup here.
		
		            if (popupOpen) {
		
		                var popup =
		                    root.consultationPopupMC;
		
		                var title =
		                    popup &&
		                    popup.popupTitle_txt
		                        ? popup.popupTitle_txt.text
		                        : "";
		
		                // Correct-answer feedback remains locked.
		                if (
		                    title === "Good Choice!" ||
		                    title === "Great Choice!"
		                ) {
		                    return;
		                }
		
		                // For a wrong-answer popup, continue normally
		                // so the product preview can be displayed.
		            }
		
		
		            if (root.productNameMC) {
		
		                root.productNameMC.visible =
		                    true;
		
		                if (
		                    root.productNameMC.productName_txt
		                ) {
		
		                    root.productNameMC.productName_txt.text =
		                        products[productID].name;
		                }
		            }
		
		
		            showProductPreview(
		                productID
		            );
		        }
		    );
		
		
		    // --------------------------------------------------------
		    // MOUSE OUT
		    // --------------------------------------------------------
		
		    product.addEventListener(
		        "mouseout",
		        function () {
		
		            if (root.productNameMC) {
		                root.productNameMC.visible =
		                    false;
		            }
		
		            hideProductPreview();
		        }
		    );
		
		
		    // --------------------------------------------------------
		    // CLICK
		    // --------------------------------------------------------
		
		    product.addEventListener(
		        "click",
		        function () {
		
		            if (!hasStarted) {
		                return;
		            }
		
		
		            // ------------------------------------------------
		            // A FEEDBACK POPUP IS ALREADY OPEN
		            // ------------------------------------------------
		
		            if (popupOpen) {
		
		                var popupTitle =
		                    root.consultationPopupMC &&
		                    root.consultationPopupMC.popupTitle_txt;
		
		
		                // If the previous selection was correct,
		                // lock the product choices.
		                if (
		                    popupTitle &&
		                    (
		                        popupTitle.text ===
		                            "Good Choice!" ||
		                        popupTitle.text ===
		                            "Great Choice!"
		                    )
		                ) {
		                    return;
		                }
		
		
		                // ------------------------------------------------
		                // WRONG ANSWER
		                //
		                // Allow the user to immediately select another
		                // product.
		                // ------------------------------------------------
		
		                closePopup();
		
		
		                showFeedback(
		                    productID
		                );
		
		
		                // The mouse is already over this product,
		                // so mouseover will not fire again.
		                //
		                // Restore the enlarged preview manually.
		                showProductPreview(
		                    productID
		                );
		
		
		                return;
		            }
		
		
		            // ------------------------------------------------
		            // NORMAL PRODUCT SELECTION
		            // ------------------------------------------------
		
		            showFeedback(
		                productID
		            );
		        }
		    );
		}
		
		
		// ============================================================
		// SETUP ALL PRODUCTS
		// ============================================================
		
		for (var productID in products) {
		    setupProduct(productID);
		}
		
		
