		// ============================================================
		// SHOW FEEDBACK
		// ============================================================
		
		function showFeedback(productID) {
		
		    var popup = getPopup();
		
		    if (!popup) {
		        return;
		    }
		
		
		    var product =
		        products[productID];
		
		    if (!product) {
		        return;
		    }
		
		
		    var goodChoice =
		        isGoodChoice(productID);
		
		    var greatChoice =
		        goodChoice &&
		        isGreatChoice(productID);
		
		
		    // --------------------------------------------------------
		    // COUNTERS
		    // --------------------------------------------------------
		
		    if (!goodChoice) {
		
		        wrongClicks++;
		
		        session.wrongClicks =
		            wrongClicks;
		
		    } else if (greatChoice) {
		
		        greatChoices++;
		
		        session.greatChoices =
		            greatChoices;
		
		    } else {
		
		        goodChoices++;
		
		        session.goodChoices =
		            goodChoices;
		    }
		
		
		    // --------------------------------------------------------
		    // TITLE
		    // --------------------------------------------------------
		
		    if (popup.popupTitle_txt) {
		
		        if (greatChoice) {
		
		            popup.popupTitle_txt.text =
		                "Great Choice!";
		
		        } else if (goodChoice) {
		
		            popup.popupTitle_txt.text =
		                "Good Choice!";
		
		        } else {
		
		            popup.popupTitle_txt.text =
		                "Consider Another Option";
		        }
		    }
		
		
		    // --------------------------------------------------------
		    // BODY
		    // --------------------------------------------------------
		
		    if (popup.popupBody_txt) {
		
		        popup.popupBody_txt.text =
		            goodChoice
		                ? getPositiveFeedback(productID)
		                : getNegativeFeedback(productID);
		    }
		
		
		    // --------------------------------------------------------
		    // IMPORTANT:
		    // Every normal product feedback hides the end screen.
		    // This prevents endRestartBtn from appearing after
		    // ordinary product clicks.
		    // --------------------------------------------------------
		
		    if (root.endScreenMC) {
		        root.endScreenMC.visible = false;
		    }
		
		
		    // --------------------------------------------------------
		    // FINAL CORRECT ANSWER
		    // --------------------------------------------------------
		
		    if (
		        goodChoice &&
		        currentClient === 4 &&
		        currentStep === getMaxStep()
		    ) {
		
		        showEndScreen();
		
		        return;
		    }
		
		
		    // --------------------------------------------------------
		    // CONTINUE
		    // --------------------------------------------------------
		
		    if (popup.continueBtn) {
		
		        popup.continueBtn.visible =
		            goodChoice &&
		            currentStep < getMaxStep();
		    }
		
		
		    // --------------------------------------------------------
		    // NEXT CLIENT
		    // --------------------------------------------------------
		
		    if (popup.nextClientBtn) {
		
		        popup.nextClientBtn.visible =
		            goodChoice &&
		            currentStep === getMaxStep() &&
		            currentClient < 4;
		    }
		
		
		    // --------------------------------------------------------
		    // RESTART
		    // Only applies to the old consultation popup.
		    // The actual end screen has its own endRestartBtn.
		    // --------------------------------------------------------
		
		    if (popup.restartBtn) {
		
		        popup.restartBtn.visible =
		            false;
		    }
		
		
		    // --------------------------------------------------------
		    // SHOW POPUP
		    // --------------------------------------------------------
		
		    popup.visible = true;
		
		    popupOpen = true;
		
		    session.popupOpen = true;
		
		
		    // Hide product name.
		    if (root.productNameMC) {
		        root.productNameMC.visible = false;
		    }
		
		    hideProductPreview();
		
		
		    // Hide client info.
		    if (root.clientInfoMC) {
		        root.clientInfoMC.visible = false;
		    }
		}
		
		
		// ============================================================
		// PRODUCT PREVIEW
		// ============================================================
		
		function showProductPreview(productID) {
		
		    if (!root.productPreviewMC) {
		        return;
		    }
		
		
		    var product =
		        getInstance(productID);
		
		    if (!product) {
		        return;
		    }
		
		
		    root.productPreviewMC.x =
		        PRODUCT_PREVIEW_X;
		
		    root.productPreviewMC.y =
		        PRODUCT_PREVIEW_Y;
		
		
		    root.productPreviewMC.removeAllChildren();
		
		
		    var preview =
		        product.clone();
		
		    if (!preview) {
		        return;
		    }
		
		
		    preview.visible = true;
		
		    preview.mouseEnabled = false;
		    preview.mouseChildren = false;
		
		
		    preview.scaleX = 1;
		    preview.scaleY = 1;
		
		
		    var bounds =
		        preview.getBounds();
		
		    if (!bounds || bounds.height <= 0) {
		        return;
		    }
		
		
		    var scale =
		        PRODUCT_PREVIEW_HEIGHT /
		        bounds.height;
		
		
		    preview.scaleX = scale;
		    preview.scaleY = scale;
		
		
		    root.productPreviewMC.addChild(
		        preview
		    );
		
		
		    var scaledBounds =
		        preview.getBounds();
		
		
		    preview.x =
		        -(
		            scaledBounds.x +
		            scaledBounds.width / 2
		        );
		
		
		    preview.y =
		        -(
		            scaledBounds.y +
		            scaledBounds.height / 2
		        );
		
		
		    root.productPreviewMC.visible =
		        true;
		}
		
		
